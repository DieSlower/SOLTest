using System;
using System.Diagnostics;
using System.IO;
using System.Threading.Tasks;
using Microsoft.Extensions.Logging;
using UnrealBuildTool;

public class SOLTest : ModuleRules
{
    // The generated build version header (SDD 46 section 11.1), under <project>/Intermediate/Generated
    private const string BUILD_VERSION_HEADER_NAME = "SOLBuildVersion.generated.h";

    // How long `git rev-list --count HEAD` may take before the count falls back to 0
    private const int GIT_TIMEOUT_MS = 5000;

    // UBT may run these rules more than once in a process, and on several threads: the header is computed once per
    // process and project, and written under this lock
    private static readonly object mBuildVersionLock = new object();
    private static string mBuildVersionProjectDir;      // The project the cached content is for
    private static string mBuildVersionContent;         // The header content computed for it

    public SOLTest(ReadOnlyTargetRules Target) : base(Target)
    {
        PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;

        // Module-root-relative includes ("Universe/SOLKepler.h"), per Docs/STYLE_GUIDE.md section 14.2
        PublicIncludePaths.Add(ModuleDirectory);

        PublicDependencyModuleNames.AddRange(new string[]
        {
            "Core",
            "CoreUObject",
            "Engine",
            "MassCore",
            "MassEntity",
        });

        PrivateDependencyModuleNames.AddRange(new string[]
        {
            "AssetRegistry",
            "EngineSettings",
            "EnhancedInput",
            "ImageCore",
            "InputCore",
            "MeshDescription",
            "Niagara",
            "RenderCore",
            "RHI",
            "Slate",
            "SlateCore",
            "StaticMeshDescription",
            "UMG",
        });

        WriteBuildVersionHeader(Target);
    }

    // Writes the build version header (the build's YYMM and the repository's commit count) into
    // Intermediate/Generated, only when its content changed, adds that folder to the private include paths when it
    // exists, and makes the git reflog an external dependency so a new commit re-runs these rules (UBT otherwise
    // reuses its cached makefile and never re-runs them). Never fails the build: SOLBuildVersion.cpp compiles without
    // the header
    private void WriteBuildVersionHeader(ReadOnlyTargetRules target)
    {
        string projectDir = target.ProjectFile != null ? target.ProjectFile.Directory.FullName
            : Path.GetFullPath(Path.Combine(ModuleDirectory, "..", ".."));
        string generatedDir = Path.Combine(projectDir, "Intermediate", "Generated");
        string headerPath = Path.Combine(generatedDir, BUILD_VERSION_HEADER_NAME);

        lock (mBuildVersionLock)
        {
            // The content once per process and project: git runs once, and every run writes the same YYMM
            if (mBuildVersionContent == null || mBuildVersionProjectDir != projectDir)
            {
                int commitCount = ReadCommitCount(projectDir);
                DateTime now = DateTime.Now;
                int yymm = (now.Year % 100) * 100 + now.Month;
                mBuildVersionContent = "// Generated by SOLTest.Build.cs (SDD 46 section 11.1); a build artefact, "
                    + "never committed\n"
                    + "#pragma once\n"
                    + "#define SOL_BUILD_YYMM " + yymm + "\n"
                    + "#define SOL_BUILD_COMMIT_COUNT " + commitCount + "\n";
                mBuildVersionProjectDir = projectDir;
            }

            // The folder first (even when the write fails, so the include path never names a missing folder), then
            // the header rewritten only when the content differs (an unchanged version recompiles nothing), through
            // a temporary file moved over it so a concurrent build never reads half a header
            string tempPath = null;
            try
            {
                Directory.CreateDirectory(generatedDir);
                if (!File.Exists(headerPath) || File.ReadAllText(headerPath) != mBuildVersionContent)
                {
                    tempPath = headerPath + "." + Environment.ProcessId + ".tmp";
                    File.WriteAllText(tempPath, mBuildVersionContent);
                    File.Move(tempPath, headerPath, true);
                    tempPath = null;
                }
            }
            catch (Exception exception)
            {
                Logger.LogWarning("SOLTest: could not write {Header}: {Message}", headerPath, exception.Message);
            }
            finally
            {
                if (tempPath != null && File.Exists(tempPath))
                {
                    try
                    {
                        File.Delete(tempPath);
                    }
                    catch (Exception)
                    {
                        // A leftover temporary file is harmless; the next write replaces it
                    }
                }
            }
        }
        if (Directory.Exists(generatedDir))
        {
            PrivateIncludePaths.Add(generatedDir);
        }

        // A commit, checkout or reset appends to the reflog, which invalidates the makefile and re-runs these rules
        string reflog = FindGitReflog(projectDir);
        if (reflog != null)
        {
            ExternalDependencies.Add(reflog);
        }
    }

    // Returns `git rev-list --count HEAD` run in the project directory, or 0 (one warning, with git's first error
    // line) when git fails; in a shallow clone the count is only the clone's depth, so it is kept with the same kind
    // of warning
    private int ReadCommitCount(string projectDir)
    {
        int count;
        try
        {
            string output = RunGit(projectDir, "rev-list --count HEAD");
            if (!int.TryParse(output.Trim(), out count) || count < 0)
            {
                throw new InvalidOperationException("git rev-list printed no count: " + FirstLine(output));
            }
        }
        catch (Exception exception)
        {
            Logger.LogWarning("SOLTest: build version commit count is 0 ({Message})", exception.Message);
            return 0;
        }

        // A shallow clone (CI checkouts) counts only the fetched commits; an older git that cannot say is not warned
        try
        {
            if (RunGit(projectDir, "rev-parse --is-shallow-repository").Trim() == "true")
            {
                Logger.LogWarning("SOLTest: build version commit count is {Count} (a shallow clone: the count is its "
                    + "depth, not the full history)", count);
            }
        }
        catch (Exception)
        {
            // No answer (an older git): the count stands without a warning
        }
        return count;
    }

    // Runs git with arguments in the project directory and returns its output; throws when it does not start, times
    // out or exits with an error (the message carries git's first error line)
    private static string RunGit(string projectDir, string arguments)
    {
        ProcessStartInfo startInfo = new ProcessStartInfo("git", arguments)
        {
            WorkingDirectory = projectDir,
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            CreateNoWindow = true,
        };
        using (Process git = Process.Start(startInfo))
        {
            if (git == null)
            {
                throw new InvalidOperationException("git did not start");
            }
            // Read asynchronously so a full pipe can never block the wait
            Task<string> output = git.StandardOutput.ReadToEndAsync();
            Task<string> error = git.StandardError.ReadToEndAsync();
            if (!git.WaitForExit(GIT_TIMEOUT_MS))
            {
                git.Kill();
                throw new TimeoutException("git " + arguments + " timed out");
            }
            if (git.ExitCode != 0)
            {
                throw new InvalidOperationException("git " + arguments + " exited with " + git.ExitCode + ": "
                    + FirstLine(error.Result));
            }
            return output.Result;
        }
    }

    // Returns the first non-empty line of a text, trimmed ("" when there is none)
    private static string FirstLine(string text)
    {
        foreach (string line in (text ?? "").Split('\n'))
        {
            if (line.Trim().Length > 0)
            {
                return line.Trim();
            }
        }
        return "";
    }

    // Returns the repository's HEAD reflog (.git/logs/HEAD; in a worktree .git is a file naming the git directory),
    // looking for .git in the project directory and then upward, or null when there is none
    private static string FindGitReflog(string projectDir)
    {
        try
        {
            for (DirectoryInfo dir = new DirectoryInfo(projectDir); dir != null; dir = dir.Parent)
            {
                string dotGit = Path.Combine(dir.FullName, ".git");
                string gitDir = null;
                if (Directory.Exists(dotGit))
                {
                    gitDir = dotGit;
                }
                else if (File.Exists(dotGit))
                {
                    // "gitdir: <path>", relative to the folder holding .git when not absolute
                    string line = File.ReadAllText(dotGit).Trim();
                    const string PREFIX = "gitdir:";
                    if (line.StartsWith(PREFIX, StringComparison.Ordinal))
                    {
                        gitDir = Path.GetFullPath(Path.Combine(dir.FullName, line.Substring(PREFIX.Length).Trim()));
                    }
                }
                if (gitDir != null)
                {
                    string reflog = Path.Combine(gitDir, "logs", "HEAD");
                    return File.Exists(reflog) ? reflog : null;
                }
            }
            return null;
        }
        catch (Exception)
        {
            return null;
        }
    }
}
