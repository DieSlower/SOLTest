    const double BELT_MIN_SEMI_MAJOR_AXIS_AU = 2.1;
    const double BELT_MAX_SEMI_MAJOR_AXIS_AU = 3.3;
    const double BELT_MAX_ECCENTRICITY = 0.3;
    const double BELT_MAX_INCLINATION_DEG = 25.0;

    const int32 DEFAULT_CLUSTER_COUNT = 300;
    const int32 DEFAULT_MIN_MEMBERS_PER_CLUSTER = 10;
    const int32 DEFAULT_MAX_MEMBERS_PER_CLUSTER = 50;
    const double DEFAULT_MIN_CLUSTER_RADIUS_M = 20000.0;
    const double DEFAULT_MAX_CLUSTER_RADIUS_M = 100000.0;

    //////////////////////////////////////////////////////////////////////////
    // Converts the catalog table to epoch elements: node and perihelion longitudes from om/w, and the mean longitude
    // propagated two-body from the catalog epoch back to J2000 with the catalog mean motion (so each asteroid sits at
    // its catalog osculating position at that epoch, mid-2026)
    TArray<FSOLAsteroidDef> RealAsteroids()
    {
        const double epochOffsetDays = BELT_CATALOG_EPOCH_JD - FSOLSimClock::J2000JulianDate;
        TArray<FSOLAsteroidDef> asteroids;
        asteroids.Reserve(UE_ARRAY_COUNT(BELT_REAL_ASTEROIDS));
        for (const FSOLRealAsteroidRow& row : BELT_REAL_ASTEROIDS)
        {
            FSOLAsteroidDef& asteroid = asteroids.AddDefaulted_GetRef();

            // Full standard asteroid designation (catalog number + name, e.g. "52 Europa"): the correct way to name
            // a specific numbered asteroid, and it guarantees no collision with a registry moon/planet of the same
            // bare name (e.g. 52 Europa vs. Jupiter's moon Europa)
            asteroid.Name = FName(*FString::Printf(TEXT("%d %s"), row.Number, row.Name));
            asteroid.RadiusM = 0.5 * row.DiameterKm * SOL::METERS_PER_KM;
            asteroid.FamilyId = INDEX_NONE;

            FSOLSecularElements& elements = asteroid.Elements;
            elements.A0AU = row.AAU;
            elements.E0 = row.E;
            elements.I0Deg = row.IDeg;
            elements.LongNode0Deg = row.LongNodeDeg;
            elements.LongPeri0Deg = SOLKepler::WrapDegrees(row.LongNodeDeg + row.ArgPeriDeg);
            elements.L0Deg = SOLKepler::WrapDegrees(row.LongNodeDeg + row.ArgPeriDeg + row.MeanAnomalyDeg
                - row.MeanMotionDegPerDay * epochOffsetDays);
            elements.LDotDegPerCy = row.MeanMotionDegPerDay * SOL::DAYS_PER_JULIAN_CENTURY;
        }
        return asteroids;
    }

    //////////////////////////////////////////////////////////////////////////
    // Returns the 3 Kirkwood gap bands in ascending order
    TArray<FSOLAxisBandAU> KirkwoodGapBandsAU()
    {
        return TArray<FSOLAxisBandAU>(BELT_KIRKWOOD_BANDS_AU, UE_ARRAY_COUNT(BELT_KIRKWOOD_BANDS_AU));
    }

    //////////////////////////////////////////////////////////////////////////
    // Returns true if the semi-major axis lies in a Kirkwood band (low inclusive, high exclusive)
    bool IsInKirkwoodGap(const double semiMajorAxisAU)
    {
        for (const FSOLAxisBandAU& band : BELT_KIRKWOOD_BANDS_AU)
        {
            if (semiMajorAxisAU >= band.LowAU && semiMajorAxisAU < band.HighAU)
            {
                return true;
            }
        }
        return false;
    }

    //////////////////////////////////////////////////////////////////////////
    // Draws clusterCount cluster centers from a stream seeded with seed, re-drawing any semi-major axis in a gap
    TArray<FSOLSecularElements> ClusterCenters(const int32 seed, const int32 clusterCount)
    {
        TArray<FSOLSecularElements> centers;
        if (clusterCount <= 0)
        {
            return centers;
        }
        centers.Reserve(clusterCount);

        const FRandomStream stream(seed);
        for (int32 cluster = 0; cluster < clusterCount; ++cluster)
        {
            FSOLSecularElements& center = centers.AddDefaulted_GetRef();

            // Rejection sampling keeps the semi-major axis out of the Kirkwood gaps
            do
            {
                center.A0AU = BeltUniform(stream, BELT_MIN_SEMI_MAJOR_AXIS_AU, BELT_MAX_SEMI_MAJOR_AXIS_AU);
            }
            while (IsInKirkwoodGap(center.A0AU));

            center.E0 = BELT_MAX_ECCENTRICITY * FMath::Pow(static_cast<double>(stream.GetFraction()),
                BELT_LOW_VALUE_SKEW_EXPONENT);
            center.I0Deg = BELT_MAX_INCLINATION_DEG * FMath::Pow(static_cast<double>(stream.GetFraction()),
                BELT_LOW_VALUE_SKEW_EXPONENT);
            center.L0Deg = BeltUniform(stream, 0.0, 360.0);
            center.LongPeri0Deg = BeltUniform(stream, 0.0, 360.0);
            center.LongNode0Deg = BeltUniform(stream, 0.0, 360.0);
            center.LDotDegPerCy = BeltMeanMotionDegPerCy(center.A0AU);
        }
        return centers;
    }

    //////////////////////////////////////////////////////////////////////////
    // Scatters each cluster's members around its ClusterCenters center with a separate, independently seeded stream
    TArray<FSOLAsteroidDef> GenerateFamilyFill(const int32 seed, const int32 clusterCount,
        const int32 minMembersPerCluster, const int32 maxMembersPerCluster, const double minClusterRadiusM,
        const double maxClusterRadiusM)
    {
        TArray<FSOLAsteroidDef> members;
        const TArray<FSOLSecularElements> centers = ClusterCenters(seed, clusterCount);
        if (centers.IsEmpty())
        {
            return members;
        }
        members.Reserve(centers.Num() * FMath::Max(maxMembersPerCluster, 0));

        const FRandomStream stream(static_cast<int32>(HashCombineFast(GetTypeHash(seed), BELT_FILL_STREAM_SALT)));
        TArray<FVector3d> centerSamplesM;
        centerSamplesM.SetNumUninitialized(BELT_COHESION_SAMPLES);
        for (int32 cluster = 0; cluster < centers.Num(); ++cluster)
        {
            const FSOLSecularElements& center = centers[cluster];
            const int32 memberCount = stream.RandRange(minMembersPerCluster, maxMembersPerCluster);
            const double clusterRadiusM = BeltUniform(stream, minClusterRadiusM, maxClusterRadiusM);

            // The center's state at J2000 and its positions over one period, shared by every member's cohesion check
            const FSOLOrbitState centerState = SOLKepler::ElementsToState(center.AtCenturies(0.0), BELT_SUN_GM, 0.0);
            const double periodCenturies = 360.0 / center.LDotDegPerCy;
            for (int32 sample = 0; sample < BELT_COHESION_SAMPLES; ++sample)
            {
                centerSamplesM[sample] = SOLKepler::ElementsToState(
                    center.AtCenturies(periodCenturies * sample / BELT_COHESION_SAMPLES), BELT_SUN_GM, 0.0).PositionM;
            }

            for (int32 memberIndex = 0; memberIndex < memberCount; ++memberIndex)
            {
                FVector3d offsetM = stream.GetUnitVector() * BeltUniform(stream, 0.0, clusterRadiusM);
                const double radiusM = BeltUniform(stream, BELT_MEMBER_MIN_RADIUS_M, BELT_MEMBER_MAX_RADIUS_M);

                // A same-period orbit wanders around the center (up to ~3.7x the initial offset at the belt's max
                // eccentricity of 0.3, numerically checked); shrink the offset until the whole relative loop fits
                // inside the cluster radius (a zero cluster radius means every member sits exactly on the center's
                // orbit)
                FSOLSecularElements elements = center;
                bool bFits = clusterRadiusM <= 0.0;
                if (!bFits)
                {
                    elements = BeltMemberElements(center, centerState, offsetM);
                }
                for (int32 rescale = 0; !bFits && rescale <= BELT_COHESION_MAX_RESCALES; ++rescale)
                {
                    const double maxSeparationM = BeltMaxSeparationM(elements, centerSamplesM, periodCenturies);
                    if (maxSeparationM <= clusterRadiusM)
                    {
                        bFits = true;
                        break;
                    }
                    offsetM *= BELT_COHESION_SHRINK_MARGIN * clusterRadiusM / maxSeparationM;
                    elements = BeltMemberElements(center, centerState, offsetM);
                }
                if (!ensureMsgf(bFits, TEXT("Asteroid family member could not be fitted inside its cluster radius")))
                {
                    elements = center;
                }

                FSOLAsteroidDef& member = members.AddDefaulted_GetRef();
                member.Name = NAME_None;
                member.Elements = elements;
                member.RadiusM = radiusM;
                member.FamilyId = cluster;
            }
        }
        return members;
    }

    //////////////////////////////////////////////////////////////////////////
    // Returns the real asteroids followed by the default-configured family fill
    TArray<FSOLAsteroidDef> GenerateBelt(const int32 seed)
    {
        TArray<FSOLAsteroidDef> belt = RealAsteroids();
        belt.Append(GenerateFamilyFill(seed, DEFAULT_CLUSTER_COUNT, DEFAULT_MIN_MEMBERS_PER_CLUSTER,
            DEFAULT_MAX_MEMBERS_PER_CLUSTER, DEFAULT_MIN_CLUSTER_RADIUS_M, DEFAULT_MAX_CLUSTER_RADIUS_M));
        return belt;
    }
