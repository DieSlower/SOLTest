    //////////////////////////////////////////////////////////////////////////
    // Returns the Sun-relative mean motion (deg per Julian century) of an orbit with the given semi-major axis (AU)
    double BeltMeanMotionDegPerCy(const double semiMajorAxisAU)
    {
        return SOLKepler::MeanMotionDegPerCy(semiMajorAxisAU * SOL::AU_M, BELT_SUN_GM);
    }

    //////////////////////////////////////////////////////////////////////////
    // Returns a uniform double in [low, high) from the stream (high itself is reachable only when low == high)
    double BeltUniform(const FRandomStream& stream, const double low, const double high)
    {
        return low + (high - low) * static_cast<double>(stream.GetFraction());
    }

    //////////////////////////////////////////////////////////////////////////
    // Converts a Sun-relative state (J2000 ecliptic) to classical epoch elements with every rate term 0
    // (LDotDegPerCy is left 0 too; the caller sets the mean motion it wants)
    FSOLSecularElements BeltStateToElements(const FSOLOrbitState& state, const double gm)
    {
        return SOLKepler::KeplerElementsToSecular(SOLKepler::StateToElements(state, gm));
    }

    //////////////////////////////////////////////////////////////////////////
    // Returns the largest sampled distance (m) between a member and its center over one shared orbital period; the
    // member has the center's semi-major axis and mean motion, so the separation repeats every period
    double BeltMaxSeparationM(const FSOLSecularElements& member, const TArray<FVector3d>& centerSamplesM,
        const double periodCenturies)
    {
        double maxDistanceM = 0.0;
        for (int32 sample = 0; sample < centerSamplesM.Num(); ++sample)
        {
            const double centuries = periodCenturies * sample / centerSamplesM.Num();
            const FVector3d memberM = SOLKepler::ElementsToState(member.AtCenturies(centuries), BELT_SUN_GM, 0.0)
                .PositionM;
            maxDistanceM = FMath::Max(maxDistanceM, (memberM - centerSamplesM[sample]).Size());
        }
        return maxDistanceM;
    }

    //////////////////////////////////////////////////////////////////////////
    // Builds a member orbit displaced offsetM from the center at J2000 with the center's orbital energy, so it shares
    // the center's semi-major axis and period and never drifts away; returns elements with the center's a and LDot
    FSOLSecularElements BeltMemberElements(const FSOLSecularElements& center, const FSOLOrbitState& centerState,
        const FVector3d& offsetM)
    {
        // Same specific energy as the center at the displaced position: rescale the center's velocity
        const FVector3d positionM = centerState.PositionM + offsetM;
        const double speedSquared = centerState.VelocityMps.SizeSquared()
            + 2.0 * BELT_SUN_GM * (1.0 / positionM.Size() - 1.0 / centerState.PositionM.Size());
        const double speedScale = FMath::Sqrt(FMath::Max(speedSquared, 0.0) / centerState.VelocityMps.SizeSquared());

        FSOLOrbitState memberState;
        memberState.PositionM = positionM;
        memberState.VelocityMps = centerState.VelocityMps * speedScale;
        FSOLSecularElements elements = BeltStateToElements(memberState, BELT_SUN_GM);

        // Pin the period exactly to the center's (the energy match leaves only rounding-level differences)
        elements.A0AU = center.A0AU;
        elements.LDotDegPerCy = center.LDotDegPerCy;
        return elements;
    }
